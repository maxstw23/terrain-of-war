let lang = 'en';
try {
  lang = new URLSearchParams(location.search).get('lang') || localStorage.getItem('tow-lang') ||
    (navigator.language?.startsWith('zh') ? 'zh' : 'en');
} catch { /* storage unavailable */ }
if (!STRINGS[lang]) lang = 'en';

export const getLang = () => lang;

export function setLang(l) {
  lang = STRINGS[l] ? l : 'en';
  try { localStorage.setItem('tow-lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
}

/** Interface string with {placeholders} filled in. */
export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

/** A scenario field in the current language, falling back to English. */
export function tr(obj, field) {
  if (!obj) return '';
  return (lang === 'zh' && obj.zh?.[field]) || obj[field] || '';
}

/** [primary, secondary] names for a place or route in the current language. */
export function names(obj) {
  const zh = obj.zh?.name || obj.nameLocal || '';
  const en = obj.name || obj.id;
  if (lang === 'zh') return zh ? [zh, en] : [en, ''];
  return [en, obj.nameLocal || ''];
}

/** Fill elements carrying data-i18n / data-i18n-title / data-i18n-ph attributes. */
export function translateDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  document.title = t('app.title');
}
